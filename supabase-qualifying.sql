-- Run this in the Supabase SQL Editor for your project.
create table if not exists public.qualifying_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 2 and 16),
  score integer not null check (score between 0 and 15),
  created_at timestamptz not null default now()
);

create index if not exists qualifying_scores_leaderboard_idx
  on public.qualifying_scores (score desc, created_at asc);

alter table public.qualifying_scores enable row level security;

drop policy if exists "Anyone can view qualifying scores" on public.qualifying_scores;
create policy "Anyone can view qualifying scores"
  on public.qualifying_scores for select to anon using (true);

drop policy if exists "Anyone can submit a qualifying score" on public.qualifying_scores;
create policy "Anyone can submit a qualifying score"
  on public.qualifying_scores for insert to anon
  with check (char_length(nickname) between 2 and 16 and score between 0 and 15);

-- There are deliberately no public update or delete policies.